export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, nl };

/** "nl", "nl-NL" and "NL" are Dutch; everything else (also empty or unknown) is English. */
export function normLang(lang: string | null | undefined): Lang {
  return typeof lang === "string" && lang.trim().toLowerCase().startsWith("nl") ? "nl" : "en";
}

/** Translates a key. `{name}` in the text is replaced by vars.name; an unknown key returns itself. */
export function t(lang: string | null | undefined, key: MessageKey, vars?: Record<string, string | number>): string {
  const text: string = MESSAGES[normLang(lang)][key] ?? en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/** "a", "a and b", "a, b and c" in the given language. */
export function joinList(lang: string | null | undefined, items: string[]): string {
  if (items.length <= 1) return items.join("");
  return `${items.slice(0, -1).join(", ")} ${t(lang, "common.and")} ${items[items.length - 1]}`;
}

export function isMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}
